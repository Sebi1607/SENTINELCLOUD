import { Monitor, TelemetryPoint, UptimeTick } from '../types/monitor';

// Generate 24 hourly uptime ticks for a monitor
const generate24hHistory = (isCurrentlyDown = false, downHours = 3): UptimeTick[] => {
  const ticks: UptimeTick[] = [];
  for (let i = 23; i >= 0; i--) {
    const hourLabel = `${(24 - i).toString().padStart(2, '0')}:00`;
    // if currently down, mark the most recent downHours as DOWN
    const isDownTick = isCurrentlyDown && i < downHours;
    ticks.push({
      hour: hourLabel,
      status: isDownTick ? 'DOWN' : 'UP',
      latency: isDownTick ? null : Math.floor(30 + Math.random() * 25),
    });
  }
  return ticks;
};

